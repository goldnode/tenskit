//! Generates `generated/` from tensdataspecs_readonly when that tree is
//! present, and fails the build if the dtype registry, the generated mapping,
//! and the format ids disagree. The spec tree is local only; the files under
//! `generated/` are tracked, so a clone without it builds from them.

use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    install_man_pages(&manifest);
    let specs = manifest.join("tensdataspecs_readonly/specs");
    let generated = manifest.join("generated");
    if specs.is_dir() {
        println!("cargo:rerun-if-changed={}", specs.display());
        generate(&manifest, &specs, &generated);
    }
    println!("cargo:rerun-if-changed={}", generated.display());

    let list = generated.join("formats.txt");
    let text = fs::read_to_string(&list).unwrap_or_else(|err| {
        panic!(
            "read {}: {err}. It is generated from tensdataspecs_readonly.",
            list.display()
        )
    });
    for line in text.lines().filter(|line| !line.starts_with('#')) {
        let (mark, id) = line
            .split_once(' ')
            .unwrap_or_else(|| panic!("{}: bad line {line:?}", list.display()));
        let cfg = id.replace('-', "_");
        println!("cargo::rustc-check-cfg=cfg(format_{cfg})");
        if mark == "+" {
            println!("cargo:rustc-cfg=format_{cfg}");
        }
    }
}

/// Write every file under `generated/` from the spec tree. A file is written
/// only when its content changes, so a build does not touch tracked files.
fn generate(manifest: &Path, specs: &Path, out: &Path) {
    let yaml_dtypes = parse_dtype_registry(&specs.join("mappings/dtypes.yaml"));
    let mapping = parse_mapping(&specs.join("mappings/dtype-mapping.json"));
    check_registry(&yaml_dtypes, &mapping);

    let formats = parse_formats(&specs.join("formats"));
    let ggml = parse_gguf_types(&specs.join("formats/gguf.yaml"));
    check_gguf(&ggml, &mapping, &yaml_dtypes);

    let safe = safetensors_rows(&yaml_dtypes, &mapping);
    let name_tables = parse_name_tables(&specs.join("mappings/metadata-mapping.yaml"));
    let generated = parse_generated_tensors(&specs.join("mappings/metadata-mapping.yaml"));
    let mut tables = render(&yaml_dtypes, &formats, &ggml, &safe, &name_tables);
    tables.push_str(&render_generated(&generated));
    write_if_changed(&out.join("spec_tables.rs"), tables.as_bytes());

    let enabled = enabled_format_ids(manifest, &formats);
    write_if_changed(
        &out.join("enabled_formats.rs"),
        render_enabled(&enabled).as_bytes(),
    );
    let mut list = String::from(
        "# Generated by build.rs from tensdataspecs_readonly and local/supported-formats.txt. Do not edit.\n\
         # Every spec format id. + is compiled in, - is not.\n",
    );
    for id in &enabled {
        list.push_str(&format!("+ {id}\n"));
    }
    for row in formats.iter().filter(|row| !enabled.contains(&row.id)) {
        list.push_str(&format!("- {}\n", row.id));
    }
    write_if_changed(&out.join("formats.txt"), list.as_bytes());

    strip_tables(&specs.join("tables"), &out.join("tables"));
    sync_dir(&specs.join("test-vectors"), &out.join("test-vectors"));
}

fn write_if_changed(path: &Path, bytes: &[u8]) {
    if fs::read(path).is_ok_and(|old| old == bytes) {
        return;
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).unwrap_or_else(|err| panic!("create {}: {err}", parent.display()));
    }
    fs::write(path, bytes).unwrap_or_else(|err| panic!("write {}: {err}", path.display()));
}

/// Make `dest` an exact copy of `source`: copy changed files, remove extra ones.
fn sync_dir(source: &Path, dest: &Path) {
    fs::create_dir_all(dest).unwrap_or_else(|err| panic!("create {}: {err}", dest.display()));
    let mut names = BTreeSet::new();
    for entry in fs::read_dir(source).unwrap_or_else(|err| panic!("read {}: {err}", source.display())) {
        let path = entry.unwrap().path();
        let name = path.file_name().unwrap().to_owned();
        if path.is_dir() {
            sync_dir(&path, &dest.join(&name));
        } else {
            let bytes = fs::read(&path).unwrap_or_else(|err| panic!("read {}: {err}", path.display()));
            write_if_changed(&dest.join(&name), &bytes);
        }
        names.insert(name);
    }
    for entry in fs::read_dir(dest).unwrap() {
        let path = entry.unwrap().path();
        if !names.contains(path.file_name().unwrap()) {
            if path.is_dir() {
                fs::remove_dir_all(&path)
            } else {
                fs::remove_file(&path)
            }
            .unwrap_or_else(|err| panic!("remove {}: {err}", path.display()));
        }
    }
}

/// The spec tables the binaries embed, minified, with the fields no code
/// reads removed. Each entry is (file, fields to drop, where): `where` is a
/// path of object keys from the root, with `*` for every member of an object
/// or array. An empty path drops top-level fields.
const STRIP: &[(&str, &[&str], &[&str])] = &[
    ("gguf-config-keys.json", &["source", "commit", "generated_by", "note", "writer_methods"], &[]),
    (
        "gguf-config-keys.json",
        &["attributes", "other_writers", "module", "model_arch", "arch", "base_reached", "super_conditional", "hf_architectures"],
        &["converters", "*"],
    ),
    ("gguf-config-keys.json", &["module", "self_attributes"], &["methods", "*"]),
    ("gguf-config-keys.json", &["at", "unpacked_from"], &["assignment_sites", "*"]),
    ("gguf-config-keys.json", &["via"], &["sequences", "*", "*"]),
    (
        "gguf-tensor-roles.json",
        &["source", "note", "resolution", "lookup_suffixes", "architecture_count", "converters_without_model_arch"],
        &[],
    ),
    ("gguf-tensor-roles.json", &["enum", "tensors_without_gguf_name"], &["architectures", "*"]),
    ("gguf-tensor-roles.json", &["module"], &["architectures", "*", "converters", "*"]),
    ("ggml-lookup-tables.json", &["source", "note", "defines"], &[]),
    (
        "ggml-lookup-tables.json",
        &["c_type", "declared_size", "count", "values_hex", "bytes_le_signed"],
        &["tables", "*"],
    ),
    ("hf-config-defaults.json", &["transformers_version", "generated_by", "note"], &[]),
    ("hf-config-defaults.json", &["config_class", "overridden"], &["model_types", "*"]),
    ("hf-config-defaults.json", &["text_config_class", "probed_keys"], &["composite_text_config", "*"]),
];

fn strip_tables(source: &Path, dest: &Path) {
    let mut files: Vec<&str> = STRIP.iter().map(|(file, _, _)| *file).collect();
    files.dedup();
    for file in files {
        let path = source.join(file);
        let text = fs::read_to_string(&path).unwrap_or_else(|err| panic!("read {}: {err}", path.display()));
        let mut value: serde_json::Value =
            serde_json::from_str(&text).unwrap_or_else(|err| panic!("{}: {err}", path.display()));
        for (_, fields, at) in STRIP.iter().filter(|(name, _, _)| *name == file) {
            drop_fields(&mut value, at, fields);
        }
        let out = serde_json::to_string(&value).unwrap();
        // The binaries parse this text again; it must give the same values.
        let back: serde_json::Value = serde_json::from_str(&out).unwrap();
        assert!(back == value, "{file}: the minified table does not read back the same");
        write_if_changed(&dest.join(file), out.as_bytes());
    }
}

fn drop_fields(value: &mut serde_json::Value, at: &[&str], fields: &[&str]) {
    let Some((first, rest)) = at.split_first() else {
        if let Some(map) = value.as_object_mut() {
            for field in fields {
                map.shift_remove(*field);
            }
        }
        return;
    };
    match (value, *first) {
        (serde_json::Value::Object(map), "*") => {
            map.values_mut().for_each(|item| drop_fields(item, rest, fields))
        }
        (serde_json::Value::Array(items), "*") => {
            items.iter_mut().for_each(|item| drop_fields(item, rest, fields))
        }
        (serde_json::Value::Object(map), key) => {
            if let Some(item) = map.get_mut(key) {
                drop_fields(item, rest, fields);
            }
        }
        _ => {}
    }
}

/// Copy `man/*.1` to `share/man/man1` beside this profile's binaries.
/// `MANPATH=target/debug/share/man man tenspile` then finds the page.
fn install_man_pages(manifest: &Path) {
    let source = manifest.join("man");
    println!("cargo:rerun-if-changed={}", source.display());
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    // OUT_DIR is target/<profile>/build/<pkg>/out, or the same under a target triple.
    let profile_dir = out_dir
        .parent()
        .and_then(Path::parent)
        .and_then(Path::parent)
        .unwrap_or_else(|| panic!("OUT_DIR is not inside target/<profile>/build"));
    let dest = profile_dir.join("share").join("man").join("man1");
    fs::create_dir_all(&dest)
        .unwrap_or_else(|err| panic!("create {}: {err}", dest.display()));
    let mut names = Vec::new();
    let entries = fs::read_dir(&source)
        .unwrap_or_else(|err| panic!("read {}: {err}", source.display()));
    for entry in entries {
        let path = entry
            .unwrap_or_else(|err| panic!("read {}: {err}", source.display()))
            .path();
        if path.extension().and_then(|ext| ext.to_str()) != Some("1") {
            continue;
        }
        println!("cargo:rerun-if-changed={}", path.display());
        let name = path
            .file_name()
            .unwrap_or_else(|| panic!("{} has no file name", path.display()));
        let target = dest.join(name);
        fs::copy(&path, &target).unwrap_or_else(|err| {
            panic!("copy {} to {}: {err}", path.display(), target.display())
        });
        names.push(name.to_os_string());
    }
    if names.is_empty() {
        panic!("{} has no section 1 pages", source.display());
    }
    let installed = fs::read_dir(&dest)
        .unwrap_or_else(|err| panic!("read {}: {err}", dest.display()));
    for entry in installed {
        let path = entry
            .unwrap_or_else(|err| panic!("read {}: {err}", dest.display()))
            .path();
        let name = path.file_name().unwrap().to_os_string();
        if !names.iter().any(|kept| kept == &name) {
            fs::remove_file(&path).ok();
        }
    }
    println!("cargo:rustc-env=TENSPILE_MAN_DIR={}", dest.display());
}

/// Ids turned on by `local/supported-formats.txt`. Each one must be a spec id
/// with a source file under `src/formats/`.
fn enabled_format_ids(manifest: &Path, formats: &[FormatRow]) -> Vec<String> {
    let path = manifest.join("local/supported-formats.txt");
    println!("cargo:rerun-if-changed={}", path.display());
    let text =
        fs::read_to_string(&path).unwrap_or_else(|err| panic!("read {}: {err}", path.display()));
    let known: BTreeSet<&str> = formats.iter().map(|row| row.id.as_str()).collect();
    let mut ids = Vec::new();
    for (line_no, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') || line.ends_with(':') {
            continue;
        }
        if !known.contains(line) {
            panic!(
                "{}:{}: {line} is not a format id in tensdataspecs_readonly/specs/formats",
                path.display(),
                line_no + 1
            );
        }
        if ids.iter().any(|id: &String| id == line) {
            panic!("{} lists {line} twice", path.display());
        }
        let source = manifest.join("src/formats").join(module_file(line));
        if !source.is_file() {
            panic!(
                "{} enables {line}, but {} is missing",
                path.display(),
                source.display()
            );
        }
        ids.push(line.to_string());
    }
    if ids.iter().any(|id| id == "npz") && !ids.iter().any(|id| id == "npy") {
        panic!("npz is enabled and npy is not; the npz reader is a zip of npy members");
    }
    ids
}

fn module_file(id: &str) -> String {
    match id {
        "raw-sidecar" => "rawtensor.rs".to_string(),
        "compressed-tensors" => "compressed_tensors.rs".to_string(),
        other => format!("{other}.rs"),
    }
}

fn module_name(id: &str) -> String {
    match id {
        "raw-sidecar" => "rawtensor".to_string(),
        "compressed-tensors" => "compressed_tensors".to_string(),
        other => other.replace('-', "_"),
    }
}

fn render_enabled(ids: &[String]) -> String {
    let mut out = String::from("// Generated by build.rs from local/supported-formats.txt. Do not edit.\n");
    let list = ids
        .iter()
        .map(|id| format!("    \"{id}\""))
        .collect::<Vec<_>>()
        .join(",\n");
    out.push_str(&format!(
        "#[allow(dead_code)]\npub static ENABLED_IDS: &[&str] = &[\n{list},\n];\n\n"
    ));
    // A relative path resolves against generated/, where this file is.
    for id in ids {
        out.push_str(&format!(
            "#[path = \"../src/formats/{}\"]\npub mod {};\n\n",
            module_file(id),
            module_name(id)
        ));
    }
    out
}

#[derive(Clone)]
struct Canon {
    id: String,
    kind: String,
    bits_num: u32,
    bits_den: u32,
    block_elements: u32,
    block_bytes: u32,
    swap_bits: u32,
    /// Sign, exponent and mantissa widths from `layout`, or empty.
    layout: Vec<u32>,
    bias: i32,
    finite_only: bool,
    nan: String,
}

#[derive(Clone)]
struct MapDtype {
    id: String,
    kind: String,
    bits: f64,
    safetensors: Vec<String>,
    npy: Vec<String>,
    gguf: Vec<String>,
}

#[derive(Clone)]
struct FormatRow {
    id: String,
    depth: String,
    category: String,
    extensions: Vec<String>,
}

#[derive(Clone)]
struct GgmlType {
    code: u32,
    name: String,
    canonical: String,
    element: bool,
    removed: bool,
    bits: u32,
    block_elements: u32,
    block_bytes: u32,
}

fn parse_dtype_registry(path: &Path) -> Vec<Canon> {
    let text =
        fs::read_to_string(path).unwrap_or_else(|err| panic!("read {}: {err}", path.display()));
    let mut rows = Vec::new();
    for line in text.lines() {
        let trimmed = line.trim();
        if !trimmed.starts_with("- {") && !trimmed.starts_with("-{") {
            continue;
        }
        let body = trimmed.trim_start_matches('-').trim();
        let fields = parse_flow_map(body);
        let get = |key: &str| {
            fields
                .iter()
                .find(|(k, _)| k == key)
                .map(|(_, value)| value.clone())
        };
        let id = get("id").unwrap_or_else(|| panic!("dtype row without id in {}", path.display()));
        let kind = get("kind").unwrap_or_else(|| panic!("{id} has no kind"));
        let bits = get("bits").unwrap_or_else(|| panic!("{id} has no bits"));
        let (bits_num, bits_den) = rational(&bits);
        let block_elements = get("block_elements")
            .map(|value| value.parse().unwrap())
            .unwrap_or(0);
        let block_bytes = get("block_bytes")
            .map(|value| value.parse().unwrap())
            .unwrap_or(0);
        let swap_bits = get("swap_bits")
            .map(|value| value.parse().unwrap())
            .unwrap_or(if bits_den == 1 { bits_num } else { 0 });
        let layout = get("layout")
            .map(|value| {
                value
                    .trim_matches(|c| c == '[' || c == ']')
                    .split(',')
                    .map(|part| part.trim().parse().unwrap())
                    .collect()
            })
            .unwrap_or_default();
        let bias = get("bias").map(|value| value.parse().unwrap()).unwrap_or(0);
        let finite_only = get("finite_only").as_deref() == Some("true");
        let nan = get("nan").unwrap_or_default();
        rows.push(Canon {
            id,
            kind,
            bits_num,
            bits_den,
            block_elements,
            block_bytes,
            swap_bits,
            layout,
            bias,
            finite_only,
            nan,
        });
    }
    if rows.is_empty() {
        panic!("{} has no dtype rows", path.display());
    }
    rows
}

fn parse_mapping(path: &Path) -> Vec<MapDtype> {
    let text =
        fs::read_to_string(path).unwrap_or_else(|err| panic!("read {}: {err}", path.display()));
    let value: serde_json::Value = serde_json::from_str(&text).unwrap();
    let rows = value["dtypes"].as_array().expect("dtypes array");
    rows.iter()
        .map(|row| {
            let formats = &row["formats"];
            MapDtype {
                id: row["id"].as_str().unwrap().to_string(),
                kind: row["kind"].as_str().unwrap().to_string(),
                bits: row["bits"].as_f64().unwrap(),
                safetensors: string_list(&formats["safetensors"]),
                npy: string_list(&formats["npy"]),
                gguf: string_list(&formats["gguf"]),
            }
        })
        .collect()
}

fn string_list(value: &serde_json::Value) -> Vec<String> {
    value
        .as_array()
        .unwrap_or(&Vec::new())
        .iter()
        .filter_map(|item| item.as_str().map(str::to_string))
        .collect()
}

fn check_registry(yaml: &[Canon], mapping: &[MapDtype]) {
    let yaml_ids: BTreeSet<_> = yaml.iter().map(|row| row.id.as_str()).collect();
    let map_ids: BTreeSet<_> = mapping.iter().map(|row| row.id.as_str()).collect();
    if yaml_ids != map_ids {
        let missing: Vec<_> = yaml_ids.difference(&map_ids).collect();
        let extra: Vec<_> = map_ids.difference(&yaml_ids).collect();
        panic!(
            "dtypes.yaml and dtype-mapping.json disagree. missing from mapping: {missing:?}. extra in mapping: {extra:?}"
        );
    }
    for row in yaml {
        let mapped = mapping.iter().find(|item| item.id == row.id).unwrap();
        if mapped.kind != row.kind {
            panic!(
                "{} kind is {} in yaml and {} in the mapping",
                row.id, row.kind, mapped.kind
            );
        }
        let bits = row.bits_num as f64 / row.bits_den as f64;
        if (bits - mapped.bits).abs() > 1e-6 {
            panic!(
                "{} bits are {bits} in yaml and {} in the mapping",
                row.id, mapped.bits
            );
        }
    }
}

fn parse_formats(dir: &Path) -> Vec<FormatRow> {
    let mut rows = Vec::new();
    let mut files: Vec<_> = fs::read_dir(dir)
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .filter(|path| path.extension().and_then(|ext| ext.to_str()) == Some("yaml"))
        .collect();
    files.sort();
    for path in files {
        let text = fs::read_to_string(&path).unwrap();
        let mut in_format = false;
        let mut id = None;
        let mut depth = None;
        let mut category = None;
        let mut extensions = Vec::new();
        for line in text.lines() {
            if !in_format {
                if line == "format:" {
                    in_format = true;
                }
                continue;
            }
            if !line.starts_with(' ') && !line.is_empty() {
                break;
            }
            let trimmed = line.trim();
            if let Some(value) = trimmed.strip_prefix("id:") {
                id = Some(unquote(value.trim()));
            } else if let Some(value) = trimmed.strip_prefix("depth:") {
                depth = Some(unquote(value.trim()));
            } else if let Some(value) = trimmed.strip_prefix("category:") {
                category = Some(unquote(value.trim()));
            } else if let Some(value) = trimmed.strip_prefix("extensions:") {
                extensions = parse_flow_list(value.trim());
            }
        }
        let id = id.unwrap_or_else(|| panic!("{} has no format.id", path.display()));
        let depth = depth.unwrap_or_else(|| panic!("{id} has no depth"));
        let category = category.unwrap_or_else(|| panic!("{id} has no category"));
        rows.push(FormatRow {
            id,
            depth,
            category,
            extensions,
        });
    }
    let mut seen = BTreeSet::new();
    for row in &rows {
        if !seen.insert(row.id.as_str()) {
            panic!("duplicate format id {}", row.id);
        }
    }
    rows
}

fn parse_gguf_types(path: &Path) -> (u32, Vec<GgmlType>) {
    let text = fs::read_to_string(path).unwrap();
    let count = text
        .lines()
        .find_map(|line| {
            let trimmed = line.trim();
            if trimmed.contains("name: COUNT") && trimmed.contains("value:") {
                let value = trimmed.split("value:").nth(1)?;
                let number: String = value
                    .trim()
                    .chars()
                    .take_while(|ch| ch.is_ascii_digit())
                    .collect();
                number.parse().ok()
            } else {
                None
            }
        })
        .unwrap_or_else(|| panic!("gguf.yaml has no GGML_TYPE_COUNT"));

    let start = text
        .find("\ndtypes:\n")
        .map(|index| index + 1)
        .unwrap_or_else(|| panic!("gguf.yaml has no dtypes section"));
    let section = &text[start..];
    let end = section
        .find("\ntensor_descriptor:")
        .unwrap_or_else(|| panic!("gguf.yaml dtypes section does not end"));
    let section = &section[..end];

    let mut types = Vec::new();
    let lines: Vec<&str> = section.lines().collect();
    let mut index = 0;
    while index < lines.len() {
        let line = lines[index].trim();
        if let Some(body) = line.strip_prefix("- {") {
            let fields = parse_flow_map(&format!("{{{body}"));
            types.push(ggml_from_fields(&fields));
            index += 1;
            continue;
        }
        if line.starts_with("- code:") {
            let mut fields = Vec::new();
            let code = line.trim_start_matches("- code:").trim().to_string();
            fields.push(("code".to_string(), code));
            index += 1;
            while index < lines.len() {
                let next = lines[index];
                if next.trim_start().starts_with("- ") && next.starts_with("  - ") {
                    break;
                }
                let trimmed = next.trim();
                if let Some((key, value)) = trimmed.split_once(':') {
                    if matches!(
                        key,
                        "name"
                            | "canonical"
                            | "storage"
                            | "status"
                            | "block_elements"
                            | "block_bytes"
                            | "bits"
                    ) && !value.trim().is_empty()
                        && !value.trim().starts_with('|')
                    {
                        fields.push((key.to_string(), value.trim().trim_matches('"').to_string()));
                    }
                }
                index += 1;
            }
            types.push(ggml_from_fields(&fields));
            continue;
        }
        index += 1;
    }
    if types.is_empty() {
        panic!("gguf.yaml produced no ggml types");
    }
    (count, types)
}

fn ggml_from_fields(fields: &[(String, String)]) -> GgmlType {
    let get = |key: &str| {
        fields
            .iter()
            .find(|(name, _)| name == key)
            .map(|(_, value)| value.clone())
    };
    let code: u32 = get("code").unwrap().parse().unwrap();
    let name = get("name").unwrap();
    let canonical = get("canonical").unwrap_or_else(|| "none".into());
    let storage = get("storage").unwrap_or_else(|| "element".into());
    let status = get("status").unwrap_or_else(|| "active".into());
    let bits_text = get("bits").unwrap_or_else(|| "0".into());
    let (num, den) = rational(&bits_text);
    let bits = if den == 1 { num } else { 0 };
    GgmlType {
        code,
        name,
        canonical,
        element: storage == "element",
        removed: status == "removed",
        bits,
        block_elements: get("block_elements")
            .map(|value| value.parse().unwrap())
            .unwrap_or(0),
        block_bytes: get("block_bytes")
            .map(|value| value.parse().unwrap())
            .unwrap_or(0),
    }
}

fn check_gguf(ggml: &(u32, Vec<GgmlType>), mapping: &[MapDtype], yaml: &[Canon]) {
    let (count, types) = ggml;
    if *count == 0 {
        panic!("GGML_TYPE_COUNT is 0");
    }
    let by_code: BTreeMap<u32, &GgmlType> = types.iter().map(|row| (row.code, row)).collect();
    for mapped in mapping {
        for entry in &mapped.gguf {
            let mut parts = entry.split_whitespace();
            let code: u32 = parts
                .next()
                .unwrap_or_else(|| panic!("bad gguf mapping entry {entry}"))
                .parse()
                .unwrap_or_else(|_| panic!("bad gguf code in {entry}"));
            let name = parts
                .next()
                .unwrap_or_else(|| panic!("bad gguf name in {entry}"));
            let row = by_code
                .get(&code)
                .unwrap_or_else(|| panic!("dtype-mapping gguf code {code} is not in gguf.yaml"));
            if row.name != name {
                panic!(
                    "gguf code {code} is {} in gguf.yaml and {name} in dtype-mapping.json",
                    row.name
                );
            }
            if row.canonical != mapped.id {
                panic!(
                    "gguf {} canonical is {} in gguf.yaml and {} in the mapping",
                    row.name, row.canonical, mapped.id
                );
            }
        }
    }
    for row in types {
        if row.removed {
            continue;
        }
        if row.canonical == "none" {
            continue;
        }
        if !yaml.iter().any(|canon| canon.id == row.canonical) {
            panic!(
                "gguf type {} canonical {} is not in dtypes.yaml",
                row.name, row.canonical
            );
        }
        let mapped = mapping
            .iter()
            .find(|item| item.id == row.canonical)
            .unwrap();
        let needle = format!("{} {}", row.code, row.name);
        if !mapped.gguf.iter().any(|entry| entry == &needle) {
            panic!("gguf type {needle} is missing from dtype-mapping.json");
        }
    }
}

struct SafeRow {
    name: String,
    bits: u32,
    numpy: Option<String>,
    canonical: String,
}

fn safetensors_rows(yaml: &[Canon], mapping: &[MapDtype]) -> Vec<SafeRow> {
    let mut rows = Vec::new();
    for canon in yaml {
        let mapped = mapping.iter().find(|item| item.id == canon.id).unwrap();
        let Some(name) = mapped.safetensors.first() else {
            continue;
        };
        if canon.bits_den != 1 {
            panic!("safetensors dtype {name} has fractional bits");
        }
        let numpy = mapped.npy.iter().find(|code| is_numpy_descr(code)).cloned();
        rows.push(SafeRow {
            name: name.clone(),
            bits: canon.bits_num,
            numpy,
            canonical: canon.id.clone(),
        });
    }
    rows.sort_by(|left, right| left.name.cmp(&right.name));
    rows
}

fn is_numpy_descr(code: &str) -> bool {
    let rest = code.trim_start_matches(['<', '>', '|', '=']);
    rest.len() >= 2
        && rest
            .chars()
            .next()
            .is_some_and(|ch| ch.is_ascii_alphabetic())
        && rest.chars().skip(1).all(|ch| ch.is_ascii_digit())
}

struct NameTable {
    id: String,
    patterns: Vec<(String, String)>,
}

/// Hugging Face <-> GGUF tensor names from metadata-mapping.yaml.
/// A `(dropped)` GGUF name is not a pair.
fn parse_name_tables(path: &Path) -> Vec<NameTable> {
    let text =
        fs::read_to_string(path).unwrap_or_else(|err| panic!("read {}: {err}", path.display()));
    let mut tables = Vec::new();
    let mut current: Option<NameTable> = None;
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        if !line.starts_with(' ') && !line.starts_with('\t') && trimmed.ends_with(':') {
            if let Some(table) = current.take() {
                if !table.patterns.is_empty() {
                    tables.push(table);
                }
            }
            current = Some(NameTable {
                id: trimmed.trim_end_matches(':').to_string(),
                patterns: Vec::new(),
            });
            continue;
        }
        if !trimmed.starts_with("- {") || !trimmed.contains("hf:") || !trimmed.contains("gguf:") {
            continue;
        }
        let Some(table) = current.as_mut() else {
            continue;
        };
        let fields = parse_flow_map(trimmed.trim_start_matches('-').trim());
        let hf = fields
            .iter()
            .find(|(key, _)| key == "hf")
            .map(|(_, value)| value.clone());
        let gguf = fields
            .iter()
            .find(|(key, _)| key == "gguf")
            .map(|(_, value)| value.clone());
        let (Some(hf), Some(gguf)) = (hf, gguf) else {
            continue;
        };
        if gguf == "(dropped)" || hf.is_empty() || gguf.is_empty() {
            continue;
        }
        table.patterns.push((hf, gguf));
    }
    if let Some(table) = current {
        if !table.patterns.is_empty() {
            tables.push(table);
        }
    }
    if tables.is_empty() {
        panic!("{} has no tensor name tables", path.display());
    }
    tables
}

fn render(
    canon: &[Canon],
    formats: &[FormatRow],
    ggml: &(u32, Vec<GgmlType>),
    safe: &[SafeRow],
    name_tables: &[NameTable],
) -> String {
    let mut out = String::from("// Generated by build.rs from tensdataspecs_readonly. Do not edit.\n\n");
    out.push_str(&format!("pub const GGML_TYPE_COUNT: u32 = {};\n\n", ggml.0));
    out.push_str("#[allow(dead_code)]\npub struct CanonRow {\n    pub id: &'static str,\n    pub kind: &'static str,\n    pub bits_num: u32,\n    pub bits_den: u32,\n    pub block_elements: u32,\n    pub block_bytes: u32,\n    pub swap_bits: u32,\n    pub layout: &'static [u32],\n    pub bias: i32,\n    pub finite_only: bool,\n    pub nan: &'static str,\n}\n\n");
    out.push_str("pub static CANON: &[CanonRow] = &[\n");
    for row in canon {
        out.push_str(&format!(
            "    CanonRow {{ id: {}, kind: {}, bits_num: {}, bits_den: {}, block_elements: {}, block_bytes: {}, swap_bits: {}, layout: &{:?}, bias: {}, finite_only: {}, nan: {} }},\n",
            rust_str(&row.id),
            rust_str(&row.kind),
            row.bits_num,
            row.bits_den,
            row.block_elements,
            row.block_bytes,
            row.swap_bits,
            row.layout,
            row.bias,
            row.finite_only,
            rust_str(&row.nan)
        ));
    }
    out.push_str("];\n\n");
    out.push_str("#[allow(dead_code)]\npub struct FormatRow {\n    pub id: &'static str,\n    pub depth: &'static str,\n    pub category: &'static str,\n    pub extensions: &'static [&'static str],\n}\n\n");
    out.push_str("#[allow(dead_code)]\npub static SPEC_FORMATS: &[FormatRow] = &[\n");
    for row in formats {
        let extensions = row
            .extensions
            .iter()
            .map(|ext| rust_str(ext))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            "    FormatRow {{ id: {}, depth: {}, category: {}, extensions: &[{extensions}] }},\n",
            rust_str(&row.id),
            rust_str(&row.depth),
            rust_str(&row.category)
        ));
    }
    out.push_str("];\n\n");
    out.push_str("#[allow(dead_code)]\npub struct GgmlRow {\n    pub code: u32,\n    pub name: &'static str,\n    pub canonical: Option<&'static str>,\n    pub element: bool,\n    pub removed: bool,\n    pub bits: u32,\n    pub block_elements: u32,\n    pub block_bytes: u32,\n}\n\n");
    out.push_str("pub static GGML_TYPES: &[GgmlRow] = &[\n");
    for row in &ggml.1 {
        let canonical = if row.canonical == "none" {
            "None".to_string()
        } else {
            format!("Some({})", rust_str(&row.canonical))
        };
        out.push_str(&format!(
            "    GgmlRow {{ code: {}, name: {}, canonical: {canonical}, element: {}, removed: {}, bits: {}, block_elements: {}, block_bytes: {} }},\n",
            row.code,
            rust_str(&row.name),
            row.element,
            row.removed,
            row.bits,
            row.block_elements,
            row.block_bytes
        ));
    }
    out.push_str("];\n\n");
    out.push_str("pub struct SafeRow {\n    pub name: &'static str,\n    pub bits: u32,\n    pub numpy: Option<&'static str>,\n    pub canonical: &'static str,\n}\n\n");
    out.push_str("pub static SAFE_ROWS: &[SafeRow] = &[\n");
    for row in safe {
        let numpy = match &row.numpy {
            Some(code) => format!("Some({})", rust_str(code)),
            None => "None".to_string(),
        };
        out.push_str(&format!(
            "    SafeRow {{ name: {}, bits: {}, numpy: {numpy}, canonical: {} }},\n",
            rust_str(&row.name),
            row.bits,
            rust_str(&row.canonical)
        ));
    }
    out.push_str("];\n\n");
    out.push_str(
        "#[allow(dead_code)]\npub struct NamePattern {\n    pub hf: &'static str,\n    pub gguf: &'static str,\n}\n\n",
    );
    out.push_str("#[allow(dead_code)]\npub struct NameTable {\n    pub id: &'static str,\n    pub patterns: &'static [NamePattern],\n}\n\n");
    out.push_str("#[allow(dead_code)]\npub static NAME_TABLES: &[NameTable] = &[\n");
    for table in name_tables {
        out.push_str(&format!(
            "    NameTable {{ id: {}, patterns: &[\n",
            rust_str(&table.id)
        ));
        for (hf, gguf) in &table.patterns {
            out.push_str(&format!(
                "        NamePattern {{ hf: {}, gguf: {} }},\n",
                rust_str(hf),
                rust_str(gguf)
            ));
        }
        out.push_str("    ] },\n");
    }
    out.push_str("];\n");
    out
}

/// metadata-mapping.yaml `gguf_generated_tensors` (GGUF-035): one row per
/// generate_extra_tensors method, as class, line, kind, tensors, and when.
fn parse_generated_tensors(path: &Path) -> Vec<Vec<(String, String)>> {
    let text =
        fs::read_to_string(path).unwrap_or_else(|err| panic!("read {}: {err}", path.display()));
    let mut rows = Vec::new();
    let mut inside = false;
    for line in text.lines() {
        if !line.starts_with(' ') && !line.trim().is_empty() {
            inside = line.trim_end() == "gguf_generated_tensors:";
            continue;
        }
        let trimmed = line.trim();
        if inside && trimmed.starts_with("- {class:") {
            let fields = parse_flow_map(trimmed.trim_start_matches('-').trim());
            for key in ["class", "line", "kind", "tensors", "when"] {
                if !fields.iter().any(|(name, _)| name == key) {
                    panic!("gguf_generated_tensors row has no {key}: {trimmed}");
                }
            }
            rows.push(fields);
        }
    }
    if rows.is_empty() {
        panic!("{} has no gguf_generated_tensors rows", path.display());
    }
    rows
}

fn render_generated(rows: &[Vec<(String, String)>]) -> String {
    let field = |row: &[(String, String)], key: &str| {
        row.iter()
            .find(|(name, _)| name == key)
            .map(|(_, value)| value.clone())
            .unwrap()
    };
    let mut out = String::from(
        "\n#[allow(dead_code)]\npub struct GeneratedTensors {\n    pub class: &'static str,\n    pub line: u64,\n    pub kind: &'static str,\n    pub tensors: &'static str,\n    pub when: &'static str,\n}\n\n#[allow(dead_code)]\npub static GENERATED_TENSORS: &[GeneratedTensors] = &[\n",
    );
    for row in rows {
        let line: u64 = field(row, "line")
            .parse()
            .unwrap_or_else(|_| panic!("gguf_generated_tensors line is not a number: {row:?}"));
        let tensors = field(row, "tensors");
        let tensors = tensors.trim_start_matches('[').trim_end_matches(']');
        out.push_str(&format!(
            "    GeneratedTensors {{ class: {}, line: {line}, kind: {}, tensors: {}, when: {} }},\n",
            rust_str(&field(row, "class")),
            rust_str(&field(row, "kind")),
            rust_str(tensors),
            rust_str(&field(row, "when"))
        ));
    }
    out.push_str("];\n");
    out
}

fn parse_flow_map(input: &str) -> Vec<(String, String)> {
    let text = input.trim();
    let text = text
        .strip_prefix('{')
        .unwrap_or_else(|| panic!("not a flow map: {input}"))
        .strip_suffix('}')
        .unwrap_or_else(|| panic!("not a flow map: {input}"));
    let bytes = text.as_bytes();
    let mut index = 0;
    let mut fields = Vec::new();
    while index < bytes.len() {
        while index < bytes.len() && (bytes[index] == b' ' || bytes[index] == b',') {
            index += 1;
        }
        if index >= bytes.len() || bytes[index] == b'}' {
            break;
        }
        let key_start = index;
        while index < bytes.len() && bytes[index] != b':' {
            index += 1;
        }
        if index >= bytes.len() {
            break;
        }
        let key = text[key_start..index].trim().to_string();
        index += 1;
        while index < bytes.len() && bytes[index] == b' ' {
            index += 1;
        }
        let value = if index < bytes.len() && (bytes[index] == b'"' || bytes[index] == b'\'') {
            let quote = bytes[index];
            index += 1;
            let start = index;
            while index < bytes.len() && bytes[index] != quote {
                index += 1;
            }
            let value = text[start..index].to_string();
            index += 1;
            value
        } else if index < bytes.len() && bytes[index] == b'[' {
            let start = index;
            while index < bytes.len() && bytes[index] != b']' {
                index += 1;
            }
            index += 1;
            text[start..index].to_string()
        } else {
            let start = index;
            while index < bytes.len() && bytes[index] != b',' {
                index += 1;
            }
            text[start..index].trim().to_string()
        };
        if !key.is_empty() {
            fields.push((key, value));
        }
    }
    fields
}

fn parse_flow_list(input: &str) -> Vec<String> {
    let text = input.trim();
    if text.is_empty() || text == "[]" {
        return Vec::new();
    }
    let inner = text
        .strip_prefix('[')
        .and_then(|text| text.strip_suffix(']'))
        .unwrap_or_else(|| panic!("not a flow list: {input}"));
    if inner.trim().is_empty() {
        return Vec::new();
    }
    inner
        .split(',')
        .map(|item| unquote(item.trim()))
        .filter(|item| !item.is_empty())
        .collect()
}

fn unquote(text: &str) -> String {
    text.trim_matches(['"', '\'']).to_string()
}

fn rational(text: &str) -> (u32, u32) {
    let text = text.trim();
    if let Some((whole, frac)) = text.split_once('.') {
        let den = 10u32.pow(frac.len() as u32);
        let num: u32 = format!("{whole}{frac}")
            .parse()
            .unwrap_or_else(|_| panic!("bad bits {text}"));
        let divisor = gcd(num, den);
        (num / divisor, den / divisor)
    } else {
        (
            text.parse().unwrap_or_else(|_| panic!("bad bits {text}")),
            1,
        )
    }
}

fn gcd(mut left: u32, mut right: u32) -> u32 {
    while right != 0 {
        let next = left % right;
        left = right;
        right = next;
    }
    left.max(1)
}

fn rust_str(text: &str) -> String {
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}
